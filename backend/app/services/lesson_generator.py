class LessonGeneratorService:
    def __init__(self, db: Session):
        self.db = db
        self.ai_provider = AIProvider(db)

    async def generate_lesson_content(
        self,
        lesson_id: int,
        context_sources: Optional[List[Dict[str, Any]]] = None
    ) -> str:
        lesson = self.db.query(Lesson).filter(Lesson.id == lesson_id).first()
        if not lesson:
            raise ValueError("Урок не найден")

        course = self.db.query(Course).filter(Course.id == lesson.course_id).first()
        course_title = course.title if course else "Вводный курс"
        learning_mode = course.learning_mode if course else "free"

        # 1. Fetch visual materials from Wikimedia Commons
        visuals = find_visual_materials(f"{lesson.title} {course_title}", limit=2)
        if not visuals:
            visuals = find_visual_materials(lesson.title, limit=2)

        # 2. Fetch educational materials / sources if not provided
        if not context_sources and course:
            from app.models.entities import CourseDocument, Document, DocumentChunk
            doc_ids = [cd.document_id for cd in course.course_documents]
            if doc_ids:
                docs = self.db.query(Document).filter(Document.id.in_(doc_ids)).all()
                context_sources = []
                for d in docs:
                    chunks = self.db.query(DocumentChunk).filter(DocumentChunk.document_id == d.id).limit(3).all()
                    chunk_text = "\n".join([c.content for c in chunks])
                    if chunk_text:
                        context_sources.append({
                            "doc_title": d.title,
                            "content": chunk_text,
                            "page": 1,
                            "section": "Материалы"
                        })

        domain = detect_subject_type(lesson.title, course_title)

        # Build presentations and quiz JSON
        presentation_slides = build_lesson_presentation_slides(lesson.title, course_title, visuals, domain)
        quiz_items = build_lesson_quiz_items(lesson.title, domain)

        # 3. AI Prompt Generation with strict visual & educational instructions
        visual_prompt_notes = ""
        if visuals:
            visual_prompt_notes = f"\nВставь в урок следующую иллюстрацию из открытой базы Wikimedia Commons:\n- URL: {visuals[0]['image_url']}\n- Описание: {visuals[0]['title']}\n- Автор: {visuals[0]['attribution']}\n- Лицензия: {visuals[0]['license']}\n"

        sources_block = ""
        if context_sources:
            sources_block = "\n\nДоступные фрагменты из учебных материалов пользователя:\n"
            for s in context_sources:
                sources_block += f"- Источник: «{s.get('doc_title', 'Документ')}» (стр. {s.get('page', 'Н/Д')}):\n{s.get('content', '')}\n\n"

        prompt = f"""
Тема урока: {lesson.title}
Описание: {lesson.description}
Курс: {course_title}
Предметная область: {domain}
Режим обучения: {learning_mode}
{visual_prompt_notes}
{sources_block}

Составь исчерпывающий, профессиональный, подробный урок без общих фраз и шаблонных шагов. Включи теорию, формулы/код, проверку знаний и проверенные источники.
"""
        try:
            content = await self.ai_provider.generate_text(
                prompt=prompt,
                system_instruction=SYSTEM_LESSON_PROMPT,
                temperature=0.6,
                request_type="lesson_generation"
            )
        except Exception as e:
            logger.info(f"AI provider failed ({e}), generating rich domain-tailored lesson.")
            content = generate_domain_tailored_lesson(lesson.title, course_title, visuals, context_sources or [], domain)

        lesson.content_markdown = content
        lesson.presentation_json = json.dumps(presentation_slides, ensure_ascii=False)
        lesson.quiz_json = json.dumps(quiz_items, ensure_ascii=False)
        if not lesson.status or lesson.status == "not_started":
            lesson.status = "in_progress"

        self.db.commit()
        self.db.refresh(lesson)
        return content
