def detect_subject_type(title: str, course_title: str) -> str:
    combined = (title + " " + course_title).lower()
    if any(k in combined for k in ["c++", "python", "массив", "алгоритм", "структур", "код", "linux", "программир", "функци", "переменн"]):
        return "programming"
    if any(k in combined for k in ["биолог", "клетк", "анатоми", "орган", "генетик", "эволюци"]):
        return "biology"
    if any(k in combined for k in ["математик", "уравнени", "квадратн", "парабол", "формул", "геометри", "алгебр"]):
        return "math"
    if any(k in combined for k in ["истори", "рим", "греци", "эпох", "войн", "импери", "узбекистан", "век"]):
        return "history"
    if any(k in combined for k in ["японск", "английск", "хираган", "язык", "грамматик", "фонетик", "немецк"]):
        return "language"
    return "general"

